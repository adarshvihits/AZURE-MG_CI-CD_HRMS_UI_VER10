function ExportToExcel() {

    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#HolidayGroupList_Count').val();
        if (pendingTableLength > 0) {
            url = "/Master/HolidayGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#HolidayGroupList_Count').val();
        if (activeTableLength > 0) {
            url = "/Master/HolidayGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#HolidayGroupList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/Master/HolidayGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}
function validateHolidayGroup() {
    var i = 0;
    if (!validateById('#Name', 'HolidayGroupName')) {
        i++;
    }
    if (!validateById('#ShortName', 'HolidayGroupShortName')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}







