var prevTab = 'ActiveTab';
var currentTab = 'ACTIVE';

function OnTabClick(Tab, TabIndex) {
    debugger;
    showSpinner();
    currentTab = TabIndex;
    $("." + prevTab).removeClass("active");
    $("." + Tab).addClass("active");
   /* var url = "/Master/ResignationReason/GetResignationReasonList";*/
    $('#tabsDropdownResignationReason').val(currentTab);
    /* $('#ResignationReasonList').load(url, { TabIndex: TabIndex }, function () { hideSpinner(); });*/

    $.ajax({

        type: 'GET',
        url: '/Master/ResignationReason/GetResignationReasonList',
        dataType: 'html',
        data: { TabIndex: TabIndex },

        success: function (result) {
            debugger
            if ($($.parseHTML(result)).filter(".Login_Session").length > 0) {
                window.location.reload();
            }
            else {
                $('#ResignationReasonList').html("");
                $('#ResignationReasonList').html(result);
            }
            hideSpinner();


        },


        error: function (xhr, textStatus, errorThrown) {
            debugger
            document.body.id = "kt_body";
            $('body').html(xhr.responseText);
            hideSpinner();

        }
    });

    prevTab = Tab;
}
