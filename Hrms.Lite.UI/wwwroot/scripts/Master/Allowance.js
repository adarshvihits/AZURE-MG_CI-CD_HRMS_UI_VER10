function ExportToExcel() {
    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#AllowanceList_Count').val();
        if (pendingTableLength > 0) {
            url = "/Master/Allowance/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#AllowanceList_Count').val();
        if (activeTableLength > 0) {
            url = "/Master/Allowance/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#AllowanceList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/Master/Allowance/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }

    }
}




function validateAllowance() {
    debugger;
    var i = 0;
    if (!validateById('#Name', 'AllowanceName')) {
        i++;
    }
    if (!validateById('#ShortName', 'AllowanceShort')) {
        i++;
    }
    if (!validateById('#AllowanceTypeCbo_Code', 'AllowanceType')) {
        i++;
    }
    if (!validateById('#ApplicableFor_Code', 'Applicable')) {
        i++;
    }
    if (!validateById('#DisplayOrder', 'Display')) {
        i++;
    }
    if (!validateById('#DisplayType_Code', 'DisplayType')) {
        i++;
    }
    
    if (i == 0)
        return true;
    else
        return false;
}
