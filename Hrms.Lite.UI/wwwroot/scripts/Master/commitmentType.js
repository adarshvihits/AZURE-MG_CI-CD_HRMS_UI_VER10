function validateCommitmentType() {
    var i = 0;
    if (!validateById('#Name', 'CommitmentTypeName')) {
        i++;
    }
    if (!validateById('#ShortName', 'CommitmentTypeShortName')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}




