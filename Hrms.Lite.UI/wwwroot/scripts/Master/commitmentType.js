function ExportToExcel() {
    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#CommitmentTypeList_Count').val();
        if (pendingTableLength > 0) {
            url = "/Master/CommitmentType/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#CommitmentTypeList_Count').val();
        if (activeTableLength > 0) {
            url = "/Master/CommitmentType/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#CommitmentTypeList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/Master/CommitmentType/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}








