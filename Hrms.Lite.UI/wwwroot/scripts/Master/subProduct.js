function clickOnExportToExcel() {

    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#SubProductList_Count').val();
        if (pendingTableLength > 0) {
            url = "/Master/SubProduct/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#SubProductList_Count').val();
        if (activeTableLength > 0) {
            url = "/Master/SubProduct/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#SubProductList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/Master/SubProduct/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}





function validateSubProduct() {
    var i = 0;
    if (!validateById('#Name', 'SubProductName')) {
        i++;
    }
    if (!validateById('#ShortName', 'SubProductShortName')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}


