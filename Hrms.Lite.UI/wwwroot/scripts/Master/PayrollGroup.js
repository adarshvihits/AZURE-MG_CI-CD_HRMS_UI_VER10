function ExportToExcel() {
    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#PayrollGroupList_Count').val();
        if (pendingTableLength > 0) {
            url = "/Master/PayrollGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#PayrollGroupList_Count').val();
        if (activeTableLength > 0) {
            url = "/Master/PayrollGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#PayrollGroupList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/Master/PayrollGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }

    }
}






function validatePayrollGroup() {
    var i = 0;
    if (!validateById('#Name', 'PayrollGroupName')) {
        i++;
    }
    if (!validateById('#ShortName', 'PayrollGroupShort')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}

