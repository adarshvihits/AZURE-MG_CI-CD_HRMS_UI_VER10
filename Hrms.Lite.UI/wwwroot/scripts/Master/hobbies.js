function ExportToExcel() {

    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#HobbyList_Count').val();
        if (pendingTableLength > 0) {
            url = "/Master/Hobby/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#HobbyList_Count').val();
        if (activeTableLength > 0) {
            url = "/Master/Hobby/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#HobbyList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/Master/Hobby/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}


function validateHobbies() {
    var i = 0;
    if (!validateById('#Name', 'HobbyName')) {
        i++;
    }
    if (!validateById('#ShortName', 'HobbyShortName')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}
