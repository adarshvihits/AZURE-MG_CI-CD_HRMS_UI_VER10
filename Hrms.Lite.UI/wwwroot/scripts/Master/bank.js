function ExportToExcel() {

    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#BankList_Count').val();
        if (pendingTableLength > 0) {
            url = "/Master/Bank/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#BankList_Count').val();
        if (activeTableLength > 0) {
            url = "/Master/Bank/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#BankList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/Master/Bank/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}


function validateBank() {
    var i = 0;
    if (!validateById('#Name', 'BankName')) {
        i++;
    }
    if (!validateById('#ShortName', 'BankShortName')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}




