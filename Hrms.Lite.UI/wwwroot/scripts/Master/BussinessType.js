function validateBussinessType() {
    var i = 0;
    if (!validateById('#Name', 'BussinessTypeName')) {
        i++;
    }
    if (!validateById('#ShortName', 'DeptShortName')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}









