function validateRewardType() {
    var i = 0;
    if (!validateById('#Name', 'RtypeName')) {
        i++;
    }
    if (!validateById('#ShortName', 'RTypeShortName')) {
        i++;
    }
  

    if (i == 0)
        return true;
    else
        return false;
}



