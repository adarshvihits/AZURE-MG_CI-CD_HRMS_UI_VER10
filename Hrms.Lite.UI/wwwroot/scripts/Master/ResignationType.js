function ExportToExcel() {
    debugger;

    if (currentTab != "APPROVAL_PENDING") {

        var TableLength = $('#ResignationTypeList_Count').val();
        if (TableLength > 0) {
            url = "/Master/ResignationType/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else {
        var PendingTableLength = $('#ResignationTypeList_Count').val();
        if (PendingTableLength > 0) {
            url = "/Master/ResignationType/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}






function validateResignationtype() {
    var i = 0;
    if (!validateById('#Name', 'ResignationName')) {
        i++;
    }
    if (!validateById('#ShortName', 'ResignationShortName')) {
        i++;
    }

    if (i == 0)
        return true;
    else
        return false;
}



