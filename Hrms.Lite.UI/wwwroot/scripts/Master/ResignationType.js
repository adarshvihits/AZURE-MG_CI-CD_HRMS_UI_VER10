

var prevTab = 'ActiveTab';
var currentTab = 'ACTIVE';


function OnTabClick(Tab, TabIndex) {
    debugger;
    showSpinner();
    currentTab = TabIndex;
    $("." + prevTab).removeClass("active");
    $("." + Tab).addClass("active");
    //var url = "/Master/ResignationType/GetResignationTypeList";
    $('#tabsDropdownResignationType').val(currentTab);
    //$('#ResignationTypeList').load(url, { TabIndex: TabIndex }, function () { hideSpinner(); });

    $.ajax({

        type: 'GET',
        url: '/Master/ResignationType/GetResignationTypeList',
        dataType: 'html',
        data: { TabIndex: TabIndex },

        success: function (result) {
            debugger
            if ($($.parseHTML(result)).filter(".Login_Session").length > 0) {
                window.location.reload();
            }
            else {
                $('#ResignationTypeList').html("");
                $('#ResignationTypeList').html(result);
            }
            hideSpinner();


        },


        error: function (xhr, textStatus, errorThrown) {
            debugger
            document.body.id = "kt_body";
            $('body').html(xhr.responseText);
            hideSpinner();

        }
    });
    prevTab = Tab;
}

