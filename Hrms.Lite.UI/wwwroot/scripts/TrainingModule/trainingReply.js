function ExportToExcel() {

    debugger;
    if (currentTab == 'APPROVAL_PENDING') {
        var pendingTableLength = $('#TrainingReplyList_Count').val();
        if (pendingTableLength > 0) {
            url = "/TrainingModule/TrainingReply/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }

    else if (currentTab == 'ACTIVE') {
        var activeTableLength = $('#TrainingReplyList_Count').val();
        if (activeTableLength > 0) {
            url = "/TrainingModule/TrainingReply/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else if (currentTab == 'INACTIVE') {
        var inActiveTableLength = $('#TrainingReplyList_Count').val();
        if (inActiveTableLength > 0) {
            url = "/TrainingModule/TrainingReply/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}