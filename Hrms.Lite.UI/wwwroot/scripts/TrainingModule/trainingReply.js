function onReplygroupChange(sender, id) {

    debugger
    var cid = $(sender).val();
    if (cid == "") {
        $(sender).addClass('is-invalid');
        $("#" + id + "").addClass('error-message');
        $("#" + id + "").html("This field is required");
    }
    else {
        $(sender).removeClass('is-invalid');
        $("#" + id + "").removeClass('error-message');
        $("#" + id + "").html("");
    }
    debugger;
    $.getJSON("/TrainingModule/TrainingReply/GetReplyGroup", { id: cid }, function (data) {

        $('.dStCode option').remove();

        $('.dStCode').append(('<option value>--Select State--</option'));


        for (var i = 0; i < data.length; i++) {
            debugger
            $('.replygrpCode').append('<option value="' + data[i].value + '">' + data[i].text + '</option');
        }

    });




}

