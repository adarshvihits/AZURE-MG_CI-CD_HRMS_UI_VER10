function validateReply() {
    var i = 0;
    if (!validateById('#Name', 'ReplyName')) {
        i++;
    }
    if (!validateById('#ReplyGroup_Code', 'Replycode')) {
        i++;
    }
    if (i == 0)
        return true;
    else
        return false;
}

