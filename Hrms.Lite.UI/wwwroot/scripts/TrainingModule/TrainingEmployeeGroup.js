function validateTrainingGroup() {
    debugger;
   
    var i = 0;


    var TableCount = $('#TrainingsList_Count').val();
    for (var j = 0; j < TableCount; j++)
    {
        if ($('#TrainingsList_' + j + '__Applicability').is(":checked") == true)
        {
            if ($('#TrainingsList_' + j + '__TrainingDuration_Code').val() == '')
            {
                i++;
            }
        }
    }

    if (i == 0) {
        return true;
    }
       
    else {
        swal.fire("please select the duration");
        return false;
    }
       
}



