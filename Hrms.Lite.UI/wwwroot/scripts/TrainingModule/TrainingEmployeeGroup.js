function onExportToExcelClick() {
    debugger;

    if (currentTab != "APPROVAL_PENDING") {

        var trainingEmployeeGroupTableLength = $('#TrainingEmployeeGroupList_Count').val();
        if (trainingEmployeeGroupTableLength > 0) {
            url = "/TrainingModule/TrainingEmployeeGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
    else {
        var trainingEmployeeGroupPendingTableLength = $('#TrainingEmployeeGroupList_Count').val();
        if (trainingEmployeeGroupPendingTableLength > 0) {
            url = "/TrainingModule/TrainingEmployeeGroup/ExportToExcel?TabIndex=" + currentTab;
            window.location.href = url;
        }
        else {
            swal.fire(NoDataFoundMsg);
        }
    }
}
