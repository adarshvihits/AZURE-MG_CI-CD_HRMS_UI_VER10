        [HttpPost]
        public async Task<IActionResult> GetCoffBalanceRptList(Filter filter)
        {
            try
            {
                CoffBalanceReport model = new CoffBalanceReport();


                Global.GlobalFilter = filter;

                if (filter.searchValue == "undefined" || filter.searchValue == null)
                {
                    filter.searchValue = "";
                }

                model = await _CoffBalanceRptService.GetList(filter);

                int totalrows = 0;
                int totalrowsafterfiltering = 0;

                if (model.CoffBalanceReportList == null || model.CoffBalanceReportList.Count() == 0)
                {


                    return Json(new
                    {
                        data = "",
                        draw = filter.draw,//Request.Form["draw"], 
                        recordsTotal = totalrows,
                        recordsFiltered = totalrows
                    });
                }




                if (model.CoffBalanceReportList.Count > 0)
                {
                    totalrows = model.CoffBalanceReportList[0].active;


                }

                if (filter.searchValue != "")
                {
                    totalrowsafterfiltering = model.CoffBalanceReportList[0].totalRecords;
                    return Json(new
                    {
                        data = model.CoffBalanceReportList,
                        draw = filter.draw,//Request.Form["draw"],//filter1.draw, //Request.Form["draw"],
                        recordsTotal = totalrows,
                        recordsFiltered = totalrows//totalrowsafterfiltering
                    });
                }
                else
                {
                    // return Json(new { data = model.EmployeeProfileList, draw = filter1.draw, recordsTotal = totalrows, recordsFiltered = totalrows });
                    return Json(new
                    {
                        data = model.CoffBalanceReportList,
                        draw = filter.draw,//Request.Form["draw"], 
                        recordsTotal = totalrows,
                        recordsFiltered = totalrows
                    });
                }


            }
            catch (Exception ex)
            {
                return View();
            }




        }


